제1장총칙

제1조 (목적) 이 약관은 회사가 제공하는 인터넷기반 문자서비스 (<?=DOMAIN?>, 이하 "서비스")의 이용조건 및 절차에 관한 기본적인 사항을 정함을 목적으로 합니다.

제2조 (약관의 적용)
1. 서비스의 이용은 전기통신서비스이용 기본약관과 이 약관을 함께 적용합니다.
2. 회사는 홈페이지(<?=DOMAIN?>)에 이용약관을 게시하는 방법으로 공지합니다.
3. 회사는 합리적인 사유가 발생될 경우에는 이 약관을 변경할 수 있으며, 약관이 변경되는 경우에는 홈페이지에 내용을 게시하여 공지합니다.

제3조 (용어의 정의) 이 약관에서 사용하는 용어의 정의는 다음과 같습니다.
1. 이용자(고객): 서비스 이용계약을 체결한 자
2. 이용신청: 회사가 정한 별도의 기준과 절차에 따라 서비스 이용을 신청하는 것
3. 이용계약: 서비스를 제공받기 위하여 회사와 이용자 간에 체결하는 계약
4. 이용정지: 일정기간 서비스 이용을 보류하는 것
5. 해지: 서비스 개통 후에 이용고객과 이용계약을 해약하는 것
6. 스팸메세지 : 정보통신망을 통해 메시지 수신자가 원하지 않는데도 불구하고 일방적으로 전송 또는 게시되는 정보
7. 불법스팸 : 정보통신망이용촉진 및 정보보호 등에 관한 법률(이하 ‘정보통신망법’이라 함) 제50조부터 제50조 8을 위반하여 전송 또는 게시되는 영리목적의 광고성 정보
8. 발신번호: 음성전화를 발신하거나 문자메시지를 발송하는 송신인의 전화번호
9. 변작번호 차단 목록: 제3자가 공공기관, 금융기관, 기업 등 정당한 전화번호로 변작하여 음성 또는 문자 발송을 방지하기 위해 한국인터넷진흥원이 관리하는 전화번호목록
10. 스미싱 : 문자메시지를 통해 휴대폰사용자의 개인정보를 도용하여 금전적인 피해를 입히는 금융사기 수법을 총칭

제4조 (계약의 성립)
1. 서비스의 이용계약은 이용자의 청약과 회사의 승낙으로 성립합니다.
2. 회사는 다음 각호의 1에 해당하는 이용신청에 대하여 서비스 이용승낙을 유보할 수 있습니다.
가. 설비에 여유가 없는 경우
나. 기술상 서비스 구현이 어려울 경우
다. 기타 회사가 필요하다고 인정되는 경우
3. 회사는 다음 각호에 해당하는 이용신청에 대하여는 이를 승낙하지 아니할 수 있으며 승낙 후에도 회사가 이러한 사실을 확인한 경우 사전통보 없이 계약을 해지할 수 있습니다.
가. 실명이 아닌 경우
나. 다른 사람의 명의를 사용하여 신청한 경우
다. 이용 신청 시 필요내용을 허위로 기재하여 신청하거나, 허위의 자료를 제출한 경우
라. 이용 신청 시 필요내용을 누락하여 기재하거나, 누락된 자료를 제출한 경우
마. 사회의 안녕질서 또는 미풍양속을 저해한 경우
바. 고객의 동의를 득하지 않은 스팸성 메시지를 전송하는 경우

제5조 (계약내용의 변경)
1. 이용고객은 이용 신청시 기재한 사항이 변경되었을 경우에는 서비스 화면의 이용고객 정보 변경란에서 변경된 사항을 수정하거나 전화,팩스,우편,방문을 통해 "회사"에게 변경사실을 통보하여야 합니다. 변경사실을 수정하지 않거나 통보하지 않아 발생한 모든 책임은 이용고객에게 있습니다.
2. 이용고객이 계약내용을 변경하고자 하는 때는 회사에 요청하여 승낙을 얻어야 합니다.

제2장 서비스의 이용

제6조 (서비스 제공)
1. 서비스 제공은 업무상 또는 기술상 특별한 지장이 없는 한 연중무휴 (1일24시간)를 원칙으로 합니다. 단, 시스템의 정기점검, 교체 및 고장, 통신의 두절, 국가비상사태, 천재지변, 정전, 서비스 설비의 장애 또는 서비스 이용의 폭주, 서비스 양도 및 폐지(휴지)등의 사유가 발생한 경우에는 서비스 제공을 일시적으로 중단할 수 있습니다.
2. 서비스 기능이 공직선거 등 공익과 관련된 사항에 영향을 미칠 수 있다고 판단되는 경우 기간을 정하여 기능의 일부를 제한할 수 있습니다.

제7조 (회사의 의무)
1. 회사는 서비스 제공과 관련하여 알고 있는 이용고객의 신상정보를 본인의 승낙 없이 제 3자에게 누설, 배포하지 않는 등 개인정보보호방침을 성실히 이행합니다. 단, 전기통신신기본법 등 법률의 규정에 의하여 국가기관의 요구가 있는 경우, 범죄에 대한 수사상의 목적이 있거나 정보통신윤리위원회의 요청이 있는 경우, 또는 기타 관계법령에서 정한 절차에 따른 요청이 있는 경우에는 그러하지 않습니다.
2. 회사는 서비스용 설비를 지속적이고, 안정적인 서비스 제공에 적합하도록 유지하여야 하며 서비스용 설비에 장애가 발생하거나 또는 그 설비가 못쓰게 된 경우 즉시 그 설비를 수리하거나 복구하여야 합니다.
3. 회사는 관련 법령이 허용하는 범위 내에서 서비스 제공목적에 맞는 서비스 이용 여부를 확인하기 위하여 상시적으로 모니터링을 실시합니다.
4. 이용고객이 전송한 메시지가 스팸 또는 불법스팸 이거나, 과학기술정보통신부 (거짓으로 표시된 전화번호로 인한 이용자 피해 예방에 등에 관한) 고시 제4조, 제5조, 제7조에 따라발신번호를 불법적으로 변작하거나, 거짓으로 표시하거나, 위법, 음란, 선량한 풍속 기타 사회질서에 위반하는 사항을 내용으로 하는 경우 "회사"는 관련 법령이 허용하는 범위 내에서 직권으로 이의 전송을 필터링 또는 차단할 수 있습니다.
5. 회사는 발신번호의 변작방지를 위해 번호인증을 통한 발신번호 사전등록서비스를 제공?운영해야 하며 회사는 이용고객의 회원가입 시 타인의 명의를 도용한 부정가입을 방지하기 위해 본인인증 서비스 사업자가 제공하는 인증방법 또는 대면인증을 통해 본인인증서비스를 제공?운영 합니다. 회사는 고객이 발신번호 사전등록 및 본인인증절차를 거친 후 서비스를 제공하여야 합니다.
6. 회사는 이용고객이 발송한 문자메시지의 발신번호가 변작번호 차단 목록에 포함되어 있거나 발신번호의 규격에 맞지 않는 전화번호의 경우 관련 법령이 허용하는 범위 내에서 해당 문자메시지의 발송 또는 전달을 차단할 수 있습니다.
7. 회사는 이용고객이 스팸 혹은 불법스팸을 전송한 사실을 확인한 경우, 관련 법령이 허용하는 범위 내에서 한국인터넷진흥원 불법스팸 대응센터 등에 관련 자료를 첨부하여 신고할 수 있습니다.
8. 회사는 전기통신사업법 및 정보통신망법 등에 따른 관계 법률에 따라 과학기술정보통신부, 방송통신위원회 및 한국인터넷진흥원 등의 정부기관이 자료 제출 요청이 있는 경우 관련 법령이 허용하는 범위 내에서 해당 자료를 제공할 수 있습니다.
9. 회사는 이용자가 서비스 화면에서 자신의 개인정보에 대한 수집, 이용 또는 제공에 대한 동의를 철회할 수 있도록 필요한 조치를 취해야 합니다
