3. 이용고객은 회사 또는 제3자의 권리를 침해하여서는 아니 됩니다. 이용고객이 자신의 서비스 이용과 관련하여 제3자와 분쟁이 발생한 경우 "회사"는 이에 대하여 책임이 없으며 모든 책임은 이용고객에게 있습니다.
4. 본 계약에 기하여 이용고객이 전송하는 정보의 내용과 관련하여 메시지 수신자 또는 제3자가 "회사"에 대하여 손해배상 등의 청구를 한 경우, 이용고객은 "회사"를 제3자의 청구로부터 면책시킬 책임이 있습니다.
5. 이용고객은 관련 법령에 따라 메시지 전송에 대하여 수신자로부터 사전 동의를 받을 경우 수신자의 동의서 및 동의철회 등 관련자료를 자체 보관 관리하여야 합니다.
