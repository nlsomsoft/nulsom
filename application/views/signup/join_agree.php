마. 서비스와 무관한 음란/상업성 메시지 발송 및 게시물 등록 행위나 법률이 정하는 범죄행위 등
바. 회사의 서비스 제공 목적 외의 용도로 서비스를 이용하거나, 제3자에게 임의로 해당 서비스를 임대하는 행위
