11. 회사는 개인정보와 관련하여 이용자의 의견을 수렴하고 불만을 처리하기 위한 절차를 마련하여야 합니다.
12. 회사는 전화, 전자우편 또는 서비스 화면의 상담창구를 통하여 이용고객의 불만사항을 접수, 처리하여야 하며 불만사항 처리는 운영자가 직접 전화하여 즉시 처리하는 것을 원칙으로 이메일 및 서면에 의한 민원 접수 처리는 24시간 이내에 처리하여야 합니다.
13. 회사는 통신장애, 서비스 설비장애, 청구요금 이의 등 회사 또는 이용고객의 귀책사유에 의한 서비스 관련 민원 접수 시 대고객 사과 또는 설명, 품질개선, 환불 등을 24시간 이내에 처리하여야 합니다.

제8조 (이용고객의 의무)
1. 이용고객은 서비스를 이용할 때 다음 각 호의 행위를 하지 않아야 하며, 정보변경시 지체 없이 회사에 통보하여 변경 하셔야 됩니다. 이를 위반한 행위에 따르는 모든 민형사상 책임을 부담할 뿐 아니라, 이와 같은 행위와 관련하여 "회사"에 손해를 끼쳤을 경우 "회사"에 대하여 손해배상의 책임을 집니다. 이용고객은 정보통신망법에 관한 법률의 광고성 정보 전송 시 의무사항 및 회사의 이용약관을 준수하여야 합니다.
가. 서비스 계약에 필요한 개인신상정보 등을 회사에 허위로 제공하는 행위
나. 타인의 서비스 ID 및 비밀번호를 도용하는 행위
다. 회사의 서비스를 이용하여 타인의 명예를 훼손시키거나 불이익을 주거나 그의 지식재산권을 침해하는 행위 또는 다른 이용고객의 정상적인 서비스를 방해하는 행위
